// ==============================================
// EXPORT
// Every format this tool emits, from the one
// resolved set.
//
// The markdown carries the most weight. An agent
// cannot hear a WAV, so parameters alone are useless
// to it — the markdown has to say when to play what,
// when NOT to, ship the synthesis function so the
// agent writes code rather than managing assets, and
// describe the relationships well enough that it can
// add a twelfth sound that belongs.
//
// Everything here reads the resolved SoundSet and
// recomputes nothing.
// ==============================================
import RUNTIME_SOURCE from "../runtime/beeps.js?raw"
import { FAMILY_BLURB, FAMILY_NAME, familyAsText } from "../shared/tools"
import { PRESETS, type PresetId } from "./presets.js"
import { DURATION_WARN_MS, frequencySpan, soundingMs } from "./resolve.js"
import {
  PAIRS,
  SOUND_SPECS,
  specFor,
  type Sound,
  type SoundId,
  type SoundSet,
} from "./sounds.js"

const round = (v: number, dp = 0) => {
  const m = Math.pow(10, dp)
  return Math.round(v * m) / m
}

/** The set as a plain data literal — what the JS export ships alongside the runtime. */
function soundsLiteral(set: SoundSet): string {
  const entries = set.sounds.map((s) => {
    const voices = s.voices.map((v) =>
      v.kind === "osc"
        ? `      { kind: "osc", waveform: ${JSON.stringify(v.waveform)}, gain: ${round(v.gain, 4)}, startOffsetMs: ${round(v.startOffsetMs, 1)},
        pitch: { startHz: ${round(v.pitch.startHz, 1)}, endHz: ${round(v.pitch.endHz, 1)}, sweepMs: ${round(v.pitch.sweepMs, 1)} },
        env: { attackMs: ${round(v.env.attackMs, 2)}, decayMs: ${round(v.env.decayMs, 2)}, sustain: ${v.env.sustain}, releaseMs: ${round(v.env.releaseMs, 2)} } }`
        : `      { kind: "noise", gain: ${round(v.gain, 4)}, startOffsetMs: ${round(v.startOffsetMs, 1)},
        env: { attackMs: ${round(v.env.attackMs, 2)}, decayMs: ${round(v.env.decayMs, 2)}, sustain: ${v.env.sustain}, releaseMs: ${round(v.env.releaseMs, 2)} } }`,
    )
    return `  ${JSON.stringify(s.id)}: {
    id: ${JSON.stringify(s.id)},
    tier: ${JSON.stringify(s.tier)},
    durationMs: ${round(s.durationMs, 1)},
    normalizedGain: ${round(s.normalizedGain, 4)},
    filter: { type: ${JSON.stringify(s.filter.type)}, cutoffHz: ${round(s.filter.cutoffHz)}, q: ${round(s.filter.q, 3)} },
    voices: [
${voices.join(",\n")}
    ],
  }`
  })
  return `{\n${entries.join(",\n")}\n}`
}

/**
 * The JS export: the runtime verbatim, plus this set as data.
 *
 * The runtime is imported with `?raw` rather than re-generated from a template,
 * so what ships is byte-for-byte the code the tool just played. A templated
 * copy would be a second implementation, and the first edit to either would
 * make the download stop matching the preview.
 */
export function toJs(set: SoundSet, url: string): string {
  return `// Generated by Beeps — ${url}
//
// Zero dependencies and zero audio assets. Everything below synthesizes at
// runtime with Web Audio.
//
// Sound is OFF until you call enable(), and enable() must run inside a real
// user gesture or the browser hands back a suspended context. Persist that
// choice per user; never turn it on for them.
//
//   import { createBeeps, SOUNDS } from "./beeps.js"
//   const beeps = createBeeps({ sounds: SOUNDS })
//   settingsToggle.addEventListener("click", () => beeps.enable())
//   button.addEventListener("click", () => beeps.play("tap"))

export const SOUNDS = ${soundsLiteral(set)}

${RUNTIME_SOURCE}`
}

/** The full resolved set, for anything that would rather parse than read. */
export function toJson(set: SoundSet, url: string): string {
  return JSON.stringify(
    {
      $schema: "https://beeps.studio/schema/v1",
      generator: "Beeps — beeps.studio",
      source: url,
      preset: set.presetId,
      baseHz: round(set.baseHz, 1),
      sounds: set.sounds.map((s) => ({
        id: s.id,
        tier: s.tier,
        durationMs: round(s.durationMs, 1),
        soundingMs: round(soundingMs(s), 1),
        normalizedGain: round(s.normalizedGain, 4),
        frequencyHz: {
          min: round(frequencySpan(s).minHz),
          max: round(frequencySpan(s).maxHz),
        },
        filter: {
          type: s.filter.type,
          cutoffHz: round(s.filter.cutoffHz),
          q: round(s.filter.q, 3),
        },
        voices: s.voices.map((v) =>
          v.kind === "osc"
            ? {
                kind: v.kind,
                waveform: v.waveform,
                gain: round(v.gain, 4),
                startOffsetMs: round(v.startOffsetMs, 1),
                pitch: {
                  startHz: round(v.pitch.startHz, 1),
                  endHz: round(v.pitch.endHz, 1),
                  sweepMs: round(v.pitch.sweepMs, 1),
                },
                env: v.env,
              }
            : { kind: v.kind, gain: round(v.gain, 4), env: v.env },
        ),
        when: specFor(s.id).when,
        whenNot: specFor(s.id).whenNot,
      })),
      notes: [
        "All sound is synthesized at runtime. There are no audio assets.",
        "Every export must sit behind a mute gate that defaults to off.",
        `Sounds are derived at musical intervals from baseHz (${round(set.baseHz)} Hz), so nothing in the set clashes.`,
      ],
    },
    null,
    2,
  )
}

/** WAV plus the snippet that plays it, for the iOS side. */
export function toNative(sound: Sound, url: string): string {
  return `// ${sound.id}.wav — generated by Beeps
// ${url}
//
// Download the WAV from the same panel and add it to your bundle.
// Mono, 16-bit, 44.1 kHz.

import AVFoundation

final class Beeps {
    /// Off until the user asks. Persist this; never default it to true.
    static var isEnabled = false

    private static var players: [String: AVAudioPlayer] = [:]

    /// Call once at launch. .ambient means UI sound never stops someone's music.
    static func configure() {
        try? AVAudioSession.sharedInstance().setCategory(.ambient, mode: .default)
        try? AVAudioSession.sharedInstance().setActive(true)
    }

    static func play(_ name: String) {
        guard isEnabled else { return }
        if let cached = players[name] {
            cached.currentTime = 0
            cached.play()
            return
        }
        guard let url = Bundle.main.url(forResource: name, withExtension: "wav"),
              let player = try? AVAudioPlayer(contentsOf: url) else { return }
        player.prepareToPlay()
        players[name] = player
        player.play()
    }
}

// Beeps.play("${sound.id}")
`
}

